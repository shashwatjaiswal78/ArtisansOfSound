/* Site search. Adds a Search button to the main menu on every page and opens a search panel.
   Index: /search-index.json (generated by tools/build.py). */
(function () {
  if (window.__aosSearch) return; window.__aosSearch = 1;
  var nav = document.querySelector('nav.nav'); if (!nav) return;
  var css = ".aos-sbtn{display:inline-flex;align-items:center;gap:8px;font:600 14px/1 inherit;font-family:inherit;color:inherit;background:transparent;border:1.5px solid currentColor;border-radius:999px;padding:9px 14px;cursor:pointer;white-space:nowrap}" +
    ".aos-sbtn{margin-left:auto}@media (min-width:901px){.nav{position:relative}.nav>ul{position:absolute;left:50%;top:50%;transform:translate(-50%,-50%);margin:0!important}}" +
    "@media (max-width:900px){.aos-sbtn{margin-left:0}.nav>.mbtn{margin-left:auto}}" +
    ".aos-sbtn:hover{opacity:.75}.aos-sbtn svg{flex:0 0 auto}" +
    "@media (max-width:700px){.aos-sbtn{padding:9px 10px}.aos-sbtn span{position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0 0 0 0)}}" +
    ".aos-sp{position:fixed;inset:0;z-index:1000;background:rgba(10,8,18,.55);display:flex;justify-content:center;align-items:flex-start;padding:10vh 12px 12px;overflow:auto}.aos-sp[hidden]{display:none}" +
    ".aos-sbox{width:100%;max-width:640px;background:#fff;color:#1B1B1D;border-radius:18px;box-shadow:0 24px 60px rgba(0,0,0,.35);overflow:hidden;font-family:'Hanken Grotesk',Arial,sans-serif}" +
    ".aos-sf{display:flex;align-items:center;gap:10px;padding:14px 16px;border-bottom:1px solid #E3DFD3}.aos-sf svg{flex:0 0 auto;color:#5B5B61}" +
    ".aos-in{flex:1;min-width:0;border:0;outline:0;font:500 18px inherit;font-family:inherit;color:#1B1B1D;background:transparent}" +
    ".aos-in::-webkit-search-cancel-button{display:none}" +
    ".aos-x{border:0;background:#EEE9DD;color:#1B1B1D;border-radius:999px;padding:7px 12px;font:600 13px inherit;font-family:inherit;cursor:pointer}" +
    ".aos-res{list-style:none;margin:0;padding:8px;max-height:min(60vh,520px);overflow:auto}.aos-res li{margin:0}" +
    ".aos-res a{display:flex;justify-content:space-between;gap:12px;align-items:baseline;padding:11px 12px;border-radius:10px;color:#1B1B1D;text-decoration:none}" +
    ".aos-res a:hover,.aos-res a:focus{background:#EEE9DD;outline:0}.aos-res b{font-weight:700;font-size:16px}" +
    ".aos-res small{color:#5B5B61;font-size:13px;white-space:nowrap}.aos-h{padding:8px 12px 2px;font:500 11px 'JetBrains Mono',monospace;letter-spacing:.12em;text-transform:uppercase;color:#5B5B61}" +
    ".aos-none{padding:16px 14px;color:#5B5B61;font-size:15px}.aos-none a{color:#1B1B1D;font-weight:600}";
  var st = document.createElement('style'); st.textContent = css; document.head.appendChild(st);

  var ICON = '<svg width="16" height="16" viewBox="0 0 20 20" aria-hidden="true"><circle cx="8.5" cy="8.5" r="5.5" fill="none" stroke="currentColor" stroke-width="2"/><path d="M13 13l5 5" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>';
  function el(t, c, h) { var e = document.createElement(t); if (c) e.className = c; if (h != null) e.innerHTML = h; return e; }
  var btn = el('button', 'aos-sbtn', ICON + '<span>Search</span>'); btn.type = 'button';
  btn.setAttribute('aria-label', 'Search artists, categories and events'); btn.setAttribute('aria-haspopup', 'dialog');
  var anchor = nav.querySelector('a.dark-pill, a.pill'); nav.insertBefore(btn, anchor || null);

  var panel = el('div', 'aos-sp'); panel.hidden = true; panel.setAttribute('role', 'dialog'); panel.setAttribute('aria-modal', 'true'); panel.setAttribute('aria-label', 'Search');
  var box = el('div', 'aos-sbox'), form = el('form', 'aos-sf'); form.setAttribute('role', 'search');
  form.innerHTML = ICON.replace('width="16" height="16"', 'width="20" height="20"');
  var input = el('input', 'aos-in'); input.type = 'search'; input.placeholder = 'Search artists, categories, events'; input.setAttribute('aria-label', 'Search the site'); input.autocomplete = 'off'; input.setAttribute('enterkeyhint', 'search');
  var close = el('button', 'aos-x', 'Close'); close.type = 'button';
  form.appendChild(input); form.appendChild(close);
  var list = el('ul', 'aos-res'); box.appendChild(form); box.appendChild(list); panel.appendChild(box); document.body.appendChild(panel);

  var data = null, loading = false;
  var QUICK = [['Category', 'All categories', '/book/'], ['Occasion', 'All occasions', '/occasions/'], ['Top list', 'Top artist lists', '/top/'], ['City', 'Cities', '/cities/'], ['Artist', 'All artists A to Z', '/artists/'], ['Guide', 'Booking guides', '/updates.html'], ['Artist', 'Join as an artist', '/join.html']];
  var BONUS = {Category: 15, 'Top list': 10, City: 8, Occasion: 6, Artist: 0, Guide: -5, Page: -2};
  function norm(s) { return String(s || '').toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim(); }
  function load() {
    if (data || loading) return; loading = true;
    fetch('/search-index.json').then(function (r) { return r.json(); }).then(function (j) {
      data = j.map(function (r) { return { t: r[0], n: r[1], u: r[2], s: r[3], tn: norm(r[1]), h: norm(r[1] + ' ' + r[3] + ' ' + r[4]) }; });
      if (input.value) render();
    }).catch(function () { loading = false; });
  }
  function row(a, title, sub) { return '<li><a href="' + a + '"><b>' + title + '</b><small>' + sub + '</small></a></li>'; }
  function esc(s) { return String(s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }
  function render() {
    var q = norm(input.value);
    if (!q) { list.innerHTML = '<li class="aos-h">Browse</li>' + QUICK.map(function (x) { return row(x[2], esc(x[1]), esc(x[0])); }).join(''); return; }
    if (!data) { list.innerHTML = '<li class="aos-none">Loading...</li>'; return; }
    var toks = q.split(' '), out = [];
    data.forEach(function (d) {
      var sc = 0;
      for (var i = 0; i < toks.length; i++) {
        var w = toks[i], p = d.h.indexOf(w); if (p < 0) return;
        var tp = d.tn.indexOf(w);
        sc += tp === 0 ? 100 : (tp > 0 && d.tn.charAt(tp - 1) === ' ') ? 70 : tp > 0 ? 50 : (d.h.charAt(p - 1) === ' ' ? 25 : 15);
      }
      if (d.tn === q) sc += 100;
      out.push([sc + (BONUS[d.t] || 0) - d.tn.length / 8, d]);
    });
    out.sort(function (a, b) { return b[0] - a[0] || (a[1].n < b[1].n ? -1 : 1); });
    var shown = out.slice(0, 12);
    list.innerHTML = shown.length ? shown.map(function (x) { return row(x[1].u, esc(x[1].n), esc(x[1].t + (x[1].s ? ' · ' + x[1].s : ''))); }).join('') +
      (out.length > 12 ? '<li class="aos-none">' + (out.length - 12) + ' more. Try a more specific search.</li>' : '')
      : '<li class="aos-none">No match. <a href="/artists/">Browse all artists</a> or <a href="/book/">categories</a>.</li>';
  }
  var lastFocus = null;
  function open() { lastFocus = document.activeElement; panel.hidden = false; document.documentElement.style.overflow = 'hidden'; load(); render(); setTimeout(function () { input.focus(); }, 0); }
  function shut() { panel.hidden = true; document.documentElement.style.overflow = ''; if (lastFocus && lastFocus.focus) { try { lastFocus.focus(); } catch (e) {} } }
  btn.addEventListener('click', open); close.addEventListener('click', shut);
  panel.addEventListener('click', function (e) { if (e.target === panel) shut(); });
  input.addEventListener('input', render); input.addEventListener('focus', load);
  form.addEventListener('submit', function (e) { e.preventDefault(); var a = list.querySelector('a'); if (a) location.href = a.getAttribute('href'); });
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && !panel.hidden) { shut(); return; }
    if (e.key === '/' && panel.hidden && !/^(INPUT|TEXTAREA|SELECT)$/.test((document.activeElement || {}).tagName || '') && !e.metaKey && !e.ctrlKey) { e.preventDefault(); open(); return; }
    if (panel.hidden || (e.key !== 'ArrowDown' && e.key !== 'ArrowUp')) return;
    var links = [].slice.call(list.querySelectorAll('a')); if (!links.length) return;
    var i = links.indexOf(document.activeElement); e.preventDefault();
    if (e.key === 'ArrowDown') (links[i + 1] || links[0]).focus(); else if (i <= 0) input.focus(); else links[i - 1].focus();
  });
})();
